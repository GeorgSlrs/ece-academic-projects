% Ορισμός των μητρώων του συστήματος κατάστασης
A = [0 1; -2 -3];
B = [0; 1];
C = [1 0];
D = 0;

% Αρχικές συνθήκες και χρονικό διάστημα
x0 = [1; 0];
t = 0:0.01:10; % 0 έως 10 δευτερόλεπτα με βήμα 0.01

% Ορισμός της εισόδου u(t) = 5cos(t)
u = 5 * cos(t);

% Δημιουργία του γραμμικού συστήματος σε μορφή κατάστασης
sys = ss(A, B, C, D);

% Προσομοίωση της απόκρισης του συστήματος
[y, t, x] = lsim(sys, u, t, x0);

% Σχεδίαση της εξόδου του συστήματος
figure;
plot(t, y);
title('Απόκριση Εξόδου του Συστήματος');
xlabel('Χρόνος (sec)');
ylabel('Έξοδος y(t)');
grid on;

% Σχεδίαση των καταστάσεων x1 και x2 σε κοινό plot με τη χρήση της εντολής hold on
figure;
plot(t, x(:,1), 'b', 'DisplayName', 'x_1(t)');
hold on;
plot(t, x(:,2), 'r', 'DisplayName', 'x_2(t)');
title('Απόκριση Καταστάσεων του Συστήματος');
xlabel('Χρόνος (sec)');
ylabel('Καταστάσεις x_1(t) και x_2(t)');
legend;
grid on;
hold off;

% Σχεδίαση των καταστάσεων x1 και x2 σε διαφορετικά subplots
figure;
subplot(2,1,1);
plot(t, x(:,1), 'b');
title('Απόκριση Κατάστασης x_1(t)');
xlabel('Χρόνος (sec)');
ylabel('x_1(t)');
grid on;

subplot(2,1,2);
plot(t, x(:,2), 'r');
title('Απόκριση Κατάστασης x_2(t)');
xlabel('Χρόνος (sec)');
ylabel('x_2(t)');
grid on;

