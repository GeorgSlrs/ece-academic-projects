% Ορισμός της συνάρτησης μεταφοράς G(s)
num = [1 -3 2];
den = [1 4 3];
G = tf(num, den);

% Υπολογισμός και εκτύπωση του DC-Gain
dcgain = dcgain(G);
disp('Το DC-Gain του συστήματος είναι:');
disp(dcgain);

% Εύρεση της βηματικής απόκρισης για t = 0:0.01:8
t = 0:0.01:8;
[y, t] = step(G, t);

% Σχεδίαση της βηματικής απόκρισης
figure;
plot(t, y);
title('Βηματική Απόκριση του Συστήματος G(s)');
xlabel('Χρόνος (sec)');
ylabel('Απόκριση Συστήματος');
grid on;
